// Run against production preview; accepts PLAYWRIGHT_MODULE, CHROMIUM_EXECUTABLE and E2E_URL.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PNG } from 'pngjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright-core');
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_EXECUTABLE ? { executablePath: process.env.CHROMIUM_EXECUTABLE } : {}), args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const tile = new PNG({ width: 256, height: 256 });
for (let i = 0; i < tile.data.length; i += 4) tile.data.set([128, 0, 0, 255], i);
const body = PNG.sync.write(tile);
const fixture = JSON.parse(readFileSync(new URL('./fixtures/v4-single-link.json', import.meta.url)));
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', e => errors.push(e.message));
  await page.route('https://www.onemap.gov.sg/**', r => r.fulfill({ contentType: 'image/png', body, headers: { 'access-control-allow-origin': '*' } }));
  await page.route('**/dem/**/*.png', r => r.fulfill({ contentType: 'image/png', body }));
  const open = async () => {
    await page.goto(process.env.E2E_URL ?? 'http://127.0.0.1:5199/friis-rf-calculator/');
    await page.getByRole('button', { name: 'Link workspace', exact: true }).click();
  };
  const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('friis-rf-planner-v3-state')));
  const commit = async (field, value) => { await field.fill(String(value)); await field.press('Enter'); };
  await open();
  await page.locator('input[type=file]').setInputFiles({ name: 'receiver.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(fixture)) });
  const card = page.locator('.selected-sensor-card');
  const panel = card.locator('.noise-floor-derivation');
  const apply = panel.getByRole('button', { name: 'Use as interference threshold', exact: true });
  assert.equal(await panel.getAttribute('open'), null, 'derivation starts collapsed');
  await panel.locator('summary').click();
  await panel.getByText('-95.0 dBm', { exact: true }).waitFor();
  await panel.getByText('-101.0 dBm', { exact: true }).waitFor();
  const before = await saved();
  await apply.click();
  let state = await saved();
  const expectedDefault = -174 + 10 * Math.log10(20e6) + 6 - 6;
  assert.ok(Math.abs(state.map.sensors[1].interferenceThresholdDbm - expectedDefault) < 1e-10);
  assert.equal(state.map.protectionMarginDb, before.map.protectionMarginDb);
  await commit(panel.getByLabel('Noise figure', { exact: false }), -1);
  await panel.getByRole('alert').waitFor();
  assert.equal(await panel.getByLabel('Noise figure', { exact: false }).inputValue(), '6');
  await commit(panel.getByLabel('Noise figure', { exact: false }), 8);
  await commit(panel.getByLabel('I/N', { exact: false }), -10);
  await commit(card.getByLabel('Channel bandwidth', { exact: false }), 40);
  await panel.getByText('-90.0 dBm', { exact: true }).waitFor();
  await panel.getByText('-100.0 dBm', { exact: true }).waitFor();
  state = await saved();
  assert.equal(state.map.sensors[1].interferenceThresholdDbm, expectedDefault, 'editing derivation does not apply it');
  assert.equal('noiseFigureDb' in state.map.sensors[1], false);
  assert.equal('interferenceToNoiseDb' in state.map.sensors[1], false);
  const beforeApply = structuredClone(state);
  await apply.click();
  state = await saved();
  const expectedCustom = -174 + 10 * Math.log10(40e6) + 8 - 10;
  assert.ok(Math.abs(state.map.sensors[1].interferenceThresholdDbm - expectedCustom) < 1e-10);
  beforeApply.map.sensors[1].interferenceThresholdDbm = expectedCustom;
  assert.deepEqual(state, beforeApply, 'applying changes only this receiver threshold');
  await open();
  assert.equal(await panel.getAttribute('open'), null);
  await panel.locator('summary').click();
  assert.equal(await panel.getByLabel('Noise figure', { exact: false }).inputValue(), '6');
  assert.equal(await panel.getByLabel('I/N', { exact: false }).inputValue(), '-6');
  assert.equal((await saved()).map.sensors[1].interferenceThresholdDbm, expectedCustom, 'applied threshold survives reload');
  await page.locator('.sensor-row').filter({ hasText: 'Rooftop TX-01' }).click();
  assert.equal(await card.locator('.noise-floor-derivation').count(), 0, 'transmitter has no noise-floor derivation');
  assert.deepEqual(errors, [], 'no uncaught page errors');
  console.log('PASS noise-floor defaults, explicit apply, bandwidth updates, invalid noise figure, local-only inputs, reload and receiver-only display');
} finally {
  await browser.close();
}
